test('Sankey works in a composition and keeps multiline captions in exported panels', async ({ page }) => {
  await page.goto('/editor')
  await page.locator('.upload-card input').setInputFiles({ name: 'flows.csv', mimeType: 'text/csv', buffer: Buffer.from('Откуда,Куда,Значение\nВсего,Семьи,90\nВсего,Учреждения,10') })
  await page.getByRole('button', { name: /Выбрать график/ }).click()
  await page.getByRole('button', { name: 'Сетка графиков', exact: true }).click()
  await page.getByRole('button', { name: '1 колонка, 3 ряда', exact: true }).click()
  for (const index of [1, 2]) {
    await page.getByRole('button', { name: `Добавить график в ячейку ${index}` }).click()
    await page.getByRole('button', { name: 'Санкей', exact: true }).click()
  }
  await page.getByRole('button', { name: /Настроить оформление/ }).click()
  const panels = page.locator('.multiples-cell .chart-canvas-shell[data-plot-kind="sankey"]')
  await expect(panels).toHaveCount(2)
  for (const panel of await panels.all()) await expect(panel).toHaveAttribute('data-render-status', 'settled')
  const caption = await panels.nth(1).locator('svg text').filter({ hasText: /^Семьи$/ }).boundingBox()
  if (!caption) throw new Error('Panel caption is missing')
  await page.mouse.click(caption.x + caption.width / 2, caption.y + caption.height / 2)
  await page.getByRole('textbox', { name: 'Текст подписи', exact: true }).fill('В семьях\n90 человек')
  await expect(panels.nth(1).locator('svg text').filter({ hasText: /^90 человек$/ })).toBeVisible()
  await page.locator('.export-menu > summary').click()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Скачать SVG' }).click()
  const svg = await readFile((await (await download).path())!, 'utf8')
  expect(svg).toContain('В семьях')
  expect(svg).toContain('90 человек')
  expect(await page.evaluate((content) => new DOMParser().parseFromString(content, 'image/svg+xml').querySelectorAll('svg svg').length, svg)).toBe(2)
})
