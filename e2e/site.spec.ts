import { expect, test } from '@playwright/test'

test('home intro expands the brand mark after the page assets are ready', async ({ page }) => {
  await page.goto('/')

  const intro = page.locator('.home-intro')
  const heroWordmark = page.locator('.hero-wordmark')
  await expect(intro).toBeVisible()
  await expect(intro).toHaveAttribute('data-stage', 'loading')
  await expect(heroWordmark).toHaveCSS('visibility', 'hidden')
  const loadingTransforms = await intro.locator('.brand-logo-letter').evaluateAll((letters) => letters.map((letter) => getComputedStyle(letter).transform))
  expect(loadingTransforms).toEqual(['none', 'none', 'none'])
  await expect(intro.locator('.brand-logo-added-stem')).toHaveCount(4)
  await expect(intro.locator('.brand-logo text')).toHaveCount(0)
  await expect(intro).toHaveAttribute('data-stage', 'expanded', { timeout: 6_000 })
  await page.waitForTimeout(1_300)
  const expandedTransforms = await intro.locator('.brand-logo-letter').evaluateAll((letters) => letters.map((letter) => getComputedStyle(letter).transform))
  expect(expandedTransforms[0]).not.toBe('none')
  expect(expandedTransforms[1]).toBe('none')
  expect(expandedTransforms[2]).not.toBe('none')
  await expect(intro).toHaveAttribute('data-stage', 'docking')
  await expect(intro).toHaveCount(0, { timeout: 3_000 })
  await expect(heroWordmark).toBeVisible()
  await expect(page.getByText('Из таблицы — в ясный график.')).toHaveCount(0)
})

