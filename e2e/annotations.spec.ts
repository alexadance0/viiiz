test('drags curve controls and snaps either endpoint to text or data with cancel and free placement', async ({ page }) => {
  await openEditor(page, true)
  await page.getByRole('button', { name: 'Текст', exact: true }).click()
  await page.getByRole('button', { name: 'Добавить в центр', exact: true }).click()
  await page.getByRole('textbox', { name: 'Текст аннотации', exact: true }).fill('Пик')
  await page.getByRole('button', { name: 'Добавить стрелку к тексту', exact: true }).click()
  await page.keyboard.press('Escape')
  const overlay = page.locator('.decoration-overlay')
  const path = overlay.locator('path.decoration-selection')
  const coordinates = async () => (await path.getAttribute('d'))!.match(/-?\d+(?:\.\d+)?/g)!.map(Number)
  const screen = async (x: number, y: number) => {
    const bounds = (await overlay.boundingBox())!
    const dimensions = (await overlay.getAttribute('viewBox'))!.split(' ').map(Number)
    return { x: bounds.x + x * bounds.width / dimensions[2], y: bounds.y + y * bounds.height / dimensions[3] }
  }
  const dragTo = async (mode: string, x: number, y: number, release = true) => {
    const handle = overlay.locator(`[data-drag-mode="${mode}"]`)
    const point = handle.locator('circle').last()
    const from = await screen(Number(await point.getAttribute('cx')), Number(await point.getAttribute('cy')))
    const to = await screen(x, y)
    await page.mouse.move(from.x, from.y); await page.mouse.down(); await page.mouse.move(to.x, to.y, { steps: 5 })
    if (release) await page.mouse.up()
  }
  const initial = await coordinates()
  await dragTo('control-first', initial[2] - 70, initial[3] - 60)
  const first = await coordinates()
  expect(first[2]).toBeCloseTo(initial[2] - 70, 0)
  expect(first[3]).toBeCloseTo(initial[3] - 60, 0)
  expect(first.slice(-2)).toEqual(initial.slice(-2))
  await dragTo('control-second', first[4] + 60, first[5] - 30)
  expect((await coordinates())[4]).toBeCloseTo(first[4] + 60, 0)

  await page.getByRole('button', { name: 'Выбрать точку на графике', exact: true }).click()
  const points = await page.locator('.annotation-placement-overlay .annotation-anchor-dot').evaluateAll((elements) => elements.map((element) => [Number(element.getAttribute('cx')), Number(element.getAttribute('cy'))]))
  await page.keyboard.press('Escape')
  // Offset the pointer slightly: snapping should still land precisely on data.
  await dragTo('end', points[2][0] + 10, points[2][1] + 8, false)
  await expect(overlay.locator('.decoration-snap-target.active')).toHaveCount(1)
  await page.screenshot({ path: '/tmp/viiiz-arrow-snap-preview.png', fullPage: true })
  await page.mouse.up()
  expect((await coordinates()).slice(-2)).toEqual(points[2])
  await expect(overlay.locator('[data-drag-mode=end]')).toHaveClass('decoration-attached-anchor')

  // Reverse the usual attachment order: start on data, end on text.
  await dragTo('start', points[0][0], points[0][1])
  expect((await coordinates()).slice(0, 2)).toEqual(points[0])
  await dragTo('end', 500, 300, false)
  const textTarget = overlay.locator('[data-snap-key^="text:"][data-snap-key$=":3"]')
  const textPoint = [Number(await textTarget.getAttribute('cx')), Number(await textTarget.getAttribute('cy'))]
  const target = await screen(textPoint[0], textPoint[1])
  await page.mouse.move(target.x, target.y, { steps: 5 })
  await expect(textTarget).toHaveClass(/active/)
  await page.mouse.up()
  expect((await coordinates()).slice(-2)).toEqual(textPoint)
  await overlay.locator('[data-drag-mode=end]').focus()
  await page.keyboard.press('Enter')
  await page.locator('.annotation-placement-overlay').getByRole('button', { name: 'Пик · Слева', exact: true }).click()
  expect((await coordinates()).slice(0, 2)).toEqual(points[0])
  expect((await coordinates()).slice(-2)).toEqual(textPoint)
  await expect(page.locator('.annotation-anchor-value')).toContainText(['2020', 'Пик'])

  await page.locator('.annotation-object-select').first().click()
  const grip = (await page.locator('.canvas-annotation.selected .annotation-content').boundingBox())!
  await page.mouse.move(grip.x + grip.width / 2, grip.y + grip.height / 2)
  await page.mouse.down(); await page.mouse.move(grip.x + grip.width / 2 + 30, grip.y + grip.height / 2 + 20); await page.mouse.up()
  await page.locator('.annotation-object-select').last().click()
  const moved = await coordinates()
  expect(moved.slice(0, 2)).toEqual(points[0])
  expect(moved[6]).toBeGreaterThan(textPoint[0])
  expect(moved[7]).toBeGreaterThan(textPoint[1])

  await dragTo('end', points[1][0], points[1][1], false)
  await expect(overlay.locator('.decoration-snap-target.active')).toHaveCount(1)
  await page.keyboard.press('Escape'); await page.mouse.up()
  expect(await coordinates()).toEqual(moved)
  await expect(overlay.locator('.decoration-snap-preview')).toHaveCount(0)

  await page.keyboard.down('Shift')
  await dragTo('end', points[1][0] + 7, points[1][1], false)
  await expect(overlay.locator('.decoration-snap-target.active')).toHaveCount(0)
  await page.mouse.up(); await page.keyboard.up('Shift')
  await expect(overlay.locator('[data-drag-mode=end]')).toHaveClass(/decoration-handle-group/)
  expect((await coordinates())[6]).toBeCloseTo(points[1][0] + 7, 0)
  const final = await coordinates()
  const svg = await exportSvg(page)
  const exported = await page.evaluate((source) => [...new DOMParser().parseFromString(source, 'image/svg+xml').querySelectorAll('path')].find((node) => node.getAttribute('d')?.includes('C') && node.getAttribute('stroke-width') === '1.5')?.getAttribute('d'), svg)
  expect(exported).toBeTruthy()
  expectArrowShaft(exported!.match(/-?\d+(?:\.\d+)?/g)!.map(Number), final)
})
