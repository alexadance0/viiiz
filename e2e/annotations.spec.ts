import { readFile, writeFile } from 'node:fs/promises'

async function openEditor(page: Page, line = false) {
  await page.goto('/editor')
  await page.locator('.upload-card input').setInputFiles({ name: 'annotation.csv', mimeType: 'text/csv', buffer: Buffer.from('Год,Значение\n2020,20\n2021,35\n2022,50') })
  await page.getByRole('button', { name: /Выбрать график/ }).click()
  if (line) await page.getByRole('button', { name: 'Линия', exact: true }).click()
  await page.getByRole('button', { name: 'Настроить оформление →' }).click()
  await page.getByRole('tab', { name: 'Аннотации и акценты', exact: true }).click()
}
async function exportSvg(page: Page) {
  await expect(page.locator('.chart-canvas-shell').first()).toHaveAttribute('data-render-status', 'settled')
  await page.locator('.export-menu > summary').click()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Скачать SVG' }).click()
  const svg = await readFile((await (await download).path())!, 'utf8')
  await page.locator('.export-menu > summary').click()
  return svg
}

function expectArrowShaft(exported: number[], attachment: number[]) {
  exported.slice(0, 6).forEach((value, index) => expect(value).toBeCloseTo(attachment[index], 0))
  // The visible shaft stops at the head's base; the attachment remains at the tip.
  const tipX = attachment[6], tipY = attachment[7]
  const angle = Math.atan2(tipY - attachment[5], tipX - attachment[4])
  const inset = 8 * Math.cos(Math.PI / 6)
  expect(exported[6]).toBeCloseTo(tipX - inset * Math.cos(angle), 0)
  expect(exported[7]).toBeCloseTo(tipY - inset * Math.sin(angle), 0)
}

